#!/usr/bin/env python3
"""Measure the GCV2's DAC as the DE1 sees it and write vcr_sim/src/dac_cal.h.

The GCV2 holds every audio cell at one code (vhs_streams aud=2, aud_mid16); the DE1's cell 0 sum is
read many times per code over JTAG. Levels are expressed in 1/16 codes of the straight-line fit, the
units draw_audio diffuses in; codes outside the sweep follow the fit.
"""
from __future__ import annotations

import argparse
import os
import subprocess
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
QUARTUS_BIN = Path(os.environ.get("QUARTUS_BIN", ""))   # unset: quartus_stp on PATH
CELL0 = slice(157, 168)                 # aud_cell0 in the 337-bit probe string (scripts/de1_ctl.sh)
OUT = ROOT / "vcr_sim/src/dac_cal.h"


def sh(*args: str) -> str:
    return subprocess.run(args, check=True, capture_output=True, text=True).stdout


def cell0_reads(n: int) -> np.ndarray:
    out = sh(str(QUARTUS_BIN / "quartus_stp"), "-t", str(ROOT / "chipset/probe.tcl"), "DE-SoC", "VSTA", f"read {n}")
    bits = [l.split()[1] for l in out.splitlines() if l.startswith("BITS ")]
    if not bits or any(len(b) != 337 for b in bits):
        raise SystemExit("unexpected probe output:\n" + out)
    return np.array([int(b[CELL0], 2) for b in bits], float)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--lo", type=int, default=12)
    ap.add_argument("--hi", type=int, default=54)
    ap.add_argument("--reads", type=int, default=40)
    args = ap.parse_args()

    gcv2 = str(ROOT / "scripts/gcv2_ctl.sh")
    codes = np.arange(args.lo, args.hi + 1)
    sums = []
    sh(gcv2, "aud", "2")
    try:
        for c in codes:
            sh(gcv2, "aud_mid16", str(16 * c))
            r = cell0_reads(args.reads)
            sums.append(r.mean())
            print(f"code {c:2d}: {r.mean():7.1f} +- {r.std() / np.sqrt(len(r)):.1f}", flush=True)
    finally:
        sh(gcv2, "aud", "1", "aud_mid16", "532")

    sums = np.array(sums)
    b, a = np.polyfit(codes, sums, 1)
    lev = np.arange(64) * 16.0
    lev[codes] = (sums - a) / b * 16
    steps = np.diff(sums) / b
    print(f"fit: {b:.2f} per code; steps {steps.min():.2f} to {steps.max():.2f} codes; "
          f"worst INL {np.abs(lev[codes] / 16 - codes).max():.2f} codes")
    body = ",\n".join("    " + ", ".join(f"{int(round(v)):4d}" for v in lev[i:i + 8]) for i in range(0, 64, 8))
    OUT.write_text("// Generated by tools/dac_cal.py: level of each DAC code as the DE1 reads it, 1/16 code of the fit.\n"
                   f"// Codes {args.lo}-{args.hi} measured; the rest follow the fit.\n"
                   f"static const int16_t dac_lev16[64] = {{\n{body},\n}};\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
